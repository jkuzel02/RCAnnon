#!/usr/bin/env bash
set -euo pipefail
# Resolve paths from this script, regardless of the caller's working directory
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"

# Target the local cluster explicitly for all Helm and kubectl operations
context="kind-local"

# Reuse the local kind cluster if it exists; otherwise create it
clusters="$(kind get clusters)"
if grep -Fxq 'local' <<< "$clusters"; then
  printf 'Reusing existing kind cluster local.\n'
else
  kind create cluster --config kind/local.yaml
fi

# Install Flux Operator
helm upgrade --install flux-operator \
  oci://ghcr.io/controlplaneio-fluxcd/charts/flux-operator \
  --kube-context "$context" \
  --version 0.61.0 \
  --namespace flux-system \
  --create-namespace \
  --wait

# Install the FluxInstance resource; check operator-managed readiness below
# Omit Helm's --wait so its custom-resource watcher does not own this check
helm upgrade --install flux-instance \
  oci://ghcr.io/controlplaneio-fluxcd/charts/flux-instance \
  --kube-context "$context" \
  --version 0.61.0 \
  --namespace flux-system \
  --set instance.cluster.size=small

# Wait for the operator to finish installing the Flux controllers
kubectl --context "$context" -n flux-system wait \
  --for=condition=Ready fluxinstance/flux \
  --timeout=3m

# Apply the Git source and root reconciliation for Flux CD
kubectl --context "$context" apply -f flux/

# Wire read-only RBAC and a container-reachable kubeconfig for local Docker Compose
kubectl --context "$context" create namespace rcannon-system --dry-run=client -o yaml | kubectl --context "$context" apply -f -
kubectl --context "$context" create namespace demo --dry-run=client -o yaml | kubectl --context "$context" apply -f -
kubectl --context "$context" apply -f rbac/rcannon-readonly.yaml

token_duration="${RCANNON_KUBE_TOKEN_DURATION:-168h}"
ro_token="$(kubectl --context "$context" -n rcannon-system create token rcannon-collector --duration="$token_duration")"
if [[ -z "$ro_token" ]]; then
  printf 'ERROR: Failed to mint read-only token for rcannon-collector.\n' >&2
  exit 1
fi

ca_data="$(kind get kubeconfig --name local --internal | awk '/certificate-authority-data:/ { print $2; exit }')"
if [[ -z "$ca_data" ]]; then
  printf 'ERROR: Failed to extract Kind cluster CA certificate data.\n' >&2
  exit 1
fi

kubeconfig_dir="../compose/kubeconfig"
mkdir -p "$kubeconfig_dir"
chmod 0755 "$kubeconfig_dir"

kubeconfig_tmp="$(mktemp "${kubeconfig_dir}/.tmp.config.XXXXXX")"
cat > "$kubeconfig_tmp" <<EOF
apiVersion: v1
kind: Config
current-context: kind-local
clusters:
  - name: kind-local
    cluster:
      server: https://local-control-plane:6443
      certificate-authority-data: ${ca_data}
contexts:
  - name: kind-local
    context:
      cluster: kind-local
      user: rcannon-collector
users:
  - name: rcannon-collector
    user:
      token: ${ro_token}
EOF
chmod 0644 "$kubeconfig_tmp"
mv "$kubeconfig_tmp" "${kubeconfig_dir}/config"

override_tmp="$(mktemp ../../.tmp.compose.override.XXXXXX)"
cat > "$override_tmp" <<'EOF'
# Auto-generated by infrastructure/k8s/bootstrap.sh (gitignored).
# Connects the rcannon service read-only to the local Kind cluster (`kind-local`).
# Remove this file if you delete the local Kind cluster (`kind delete cluster --name local`).
services:
  rcannon:
    networks:
      - kind
    volumes:
      - ./infrastructure/compose/kubeconfig:/etc/rcannon/kubeconfig:ro
    environment:
      RCANNON_KUBECONFIG_PATH: /etc/rcannon/kubeconfig/config
      RCANNON_KUBE_CONTEXT: kind-local
      RCANNON_TARGET_ALIAS: lab

networks:
  kind:
    external: true
EOF
chmod 0644 "$override_tmp"
mv "$override_tmp" ../../compose.override.yaml

printf 'Configured read-only Kind access in infrastructure/compose/kubeconfig/config and compose.override.yaml.\n'
printf 'Start the RCAnnon API with: docker compose up -d\n'
printf 'Include LibreChat with: docker compose --profile librechat up -d\n'
